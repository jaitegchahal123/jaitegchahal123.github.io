"""# Part 2.4: Implementing a Class-conditioned UNet"""

class ClassConditionalUNet(nn.Module):
    def __init__(
        self,
        in_channels: int,
        num_classes: int,
        num_hiddens: int,
    ):
        super().__init__()
        # ===== your code here! ====
        self.in_channels = in_channels
        self.num_hiddens = num_hiddens
        self.num_classes = num_classes

        D = num_hiddens

        # Encoder
        self.enc1 = ConvBlock(in_channels, D)   # 28x28
        self.enc2 = DownBlock(D, D)            # 14x14
        self.enc3 = DownBlock(D, D)            # 7x7

        # Bottleneck
        self.flatten = Flatten()
        self.mid = ConvBlock(D, D)
        self.unflatten = Unflatten(D)

        # Decoder with skips
        self.dec3 = UpBlock(D * 2, D)
        self.dec2 = UpBlock(D * 2, D)
        self.out_conv = nn.Conv2d(D * 2, in_channels, kernel_size=3, stride=1, padding=1)

        # Time embedding
        self.time_mlp = FCBlock(1, D)

        # Class embedding
        self.class_emb = nn.Embedding(num_classes, D)
        # ===== end of code ====

    def forward(
        self,
        x: torch.Tensor,
        c: torch.Tensor,
        t: torch.Tensor,
        mask: torch.Tensor | None = None,
    ) -> torch.Tensor:
        """
        Args:
            x: (N, C, H, W) input tensor.
            c: (N,) int64 condition tensor.
            t: (N,) normalized time tensor.
            mask: (N,) mask tensor. If not None, mask out condition when mask == 0.

        Returns:
            (N, C, H, W) output tensor.
        """
        assert x.shape[-2:] == (28, 28), "Expect input shape to be (28, 28)."
        # ===== your code here! ====
        N = x.shape[0]

        # Encoder
        x1 = self.enc1(x)
        x2 = self.enc2(x1)
        x3 = self.enc3(x2)

        # Bottleneck: flatten
        xb = self.flatten(x3)   # (N, D, 1, 1)

        # Time embedding
        t_in = t.view(N, 1)
        t_emb = self.time_mlp(t_in)   # (N, D)

        # Class embedding
        c_emb = self.class_emb(c)     # (N, D)

        if mask is not None:
            # mask: 1 -> keep class, 0 -> drop class (unconditional)
            mask_ = mask.view(N, 1)
            c_emb = c_emb * mask_

        total_emb = t_emb + c_emb      # (N, D)
        total_emb = total_emb.view(N, self.num_hiddens, 1, 1)

        xb = xb + total_emb
        xb = self.mid(xb)
        xb = self.unflatten(xb)

        # Decoder with skips
        d3 = self.dec3(torch.cat([xb, x3], dim=1))
        d2 = self.dec2(torch.cat([d3, x2], dim=1))
        out = self.out_conv(torch.cat([d2, x1], dim=1))
        return out
        # ===== end of code ====
        raise NotImplementedError()

def class_fm_forward(
    unet: ClassConditionalUNet,
    x_1: torch.Tensor,
    c: torch.Tensor,
    p_uncond: float,
    num_ts: int,
) -> torch.Tensor:
    """Algorithm 3

    Args:
        unet: ClassConditionalUNet
        x_1: (N, C, H, W) input tensor.
        c: (N,) int64 condition tensor.
        p_uncond: float, probability of unconditioning the condition.
        num_ts: int, number of timesteps.

    Returns:
        (,) loss.
    """
    unet.train()
    # ===== your code here! ====
    device = x_1.device
    N = x_1.shape[0]

    # Noise endpoint x_0 ~ N(0, I)
    x_0 = torch.randn_like(x_1)

    # Sample t ~ U(0,1)
    t = torch.rand(N, device=device)
    t_broadcast = t.view(N, 1, 1, 1)

    # Path
    x_t = (1.0 - t_broadcast) * x_0 + t_broadcast * x_1

    # Target velocity
    v_target = x_1 - x_0

    # Bernoulli mask for unconditioning (0 = uncond, 1 = cond)
    mask = (torch.rand(N, device=device) > p_uncond).float()

    # Predicted velocity
    v_pred = unet(x_t, c, t, mask=mask)

    loss = torch.mean((v_pred - v_target) ** 2)
    return loss
    # ===== end of code ====
    raise NotImplementedError()

@torch.inference_mode()
def class_fm_sample(
    unet: ClassConditionalUNet,
    c: torch.Tensor,
    img_wh: tuple[int, int],
    num_ts: int,
    guidance_scale: float = 5.0,
    seed: int = 0,
) -> torch.Tensor:
    """Algorithm 4

    Args:
        unet: ClassConditionalUNet
        c: (N,) int64 condition tensor. Only for class-conditional
        img_wh: (H, W) output image width and height.
        num_ts: int, number of timesteps.
        guidance_scale: float, CFG scale.
        seed: int, random seed.

    Returns:
        (N, C, H, W) final sample.
        (N, T_animation, C, H, W) caches.
    """
    unet.eval()
    # ===== your code here! ====
    device = next(unet.parameters()).device
    H, W = img_wh
    N = c.shape[0]
    C = 1

    torch.manual_seed(seed)

    # Start from noise at t=0
    x = torch.randn(N, C, H, W, device=device)
    dt = 1.0 / num_ts

    caches = []

    for k in range(num_ts):
        t_val = k / num_ts
        t = torch.full((N,), t_val, device=device)

        # Unconditional (mask = 0)
        mask_uncond = torch.zeros(N, device=device)
        v_uncond = unet(x, c, t, mask=mask_uncond)

        # Conditional (mask = 1)
        mask_cond = torch.ones(N, device=device)
        v_cond = unet(x, c, t, mask=mask_cond)

        # CFG
        v = v_uncond + guidance_scale * (v_cond - v_uncond)

        # Euler integration
        x = x + dt * v

        caches.append(x.detach().cpu())

    final = x.detach().cpu()                            # (N, C, H, W)
    caches = torch.stack(caches, dim=1)                # (T, N, C, H, W)
    caches = caches.permute(1, 0, 2, 3, 4)             # (N, T, C, H, W)
    return final, caches
    # ===== end of code ====
    raise NotImplementedError()

class ClassConditionalFM(nn.Module):
    def __init__(
        self,
        unet: ClassConditionalUNet,
        num_ts: int = 300,
        p_uncond: float = 0.1,
    ):
        super().__init__()
        self.unet = unet
        self.num_ts = num_ts
        self.p_uncond = p_uncond

    def forward(self, x: torch.Tensor, c: torch.Tensor) -> torch.Tensor:
        """
        Args:
            x: (N, C, H, W) input tensor.
            c: (N,) int64 condition tensor.

        Returns:
            (,) loss.
        """
        return class_fm_forward(
            self.unet, x, c, self.p_uncond, self.num_ts
        )

    @torch.inference_mode()
    def sample(
        self,
        c: torch.Tensor,
        img_wh: tuple[int, int],
        guidance_scale: float = 5.0,
        seed: int = 0,
    ):
        return class_fm_sample(
            self.unet, c, img_wh, self.num_ts, guidance_scale, seed
        )

