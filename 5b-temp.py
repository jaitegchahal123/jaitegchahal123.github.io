"""## Implementing Unconditional UNet"""

class UnconditionalUNet(nn.Module):
    def __init__(
        self,
        in_channels: int,
        num_hiddens: int,
    ):
        super().__init__()
        # ===== your code here! ====
        D = num_hiddens

        # Encoder
        self.enc1 = ConvBlock(in_channels, D)   # 28x28
        self.enc2 = DownBlock(D, D)            # 14x14
        self.enc3 = DownBlock(D, D)            # 7x7

        # Bottleneck
        self.flatten = Flatten()               # 1x1
        self.mid = ConvBlock(D, D)             # 1x1 conv block
        self.unflatten = Unflatten(D)          # back to 7x7

        # Decoder with skip connections
        self.dec3 = UpBlock(D * 2, D)          # 7x7 -> 14x14
        self.dec2 = UpBlock(D * 2, D)          # 14x14 -> 28x28
        self.out_conv = nn.Conv2d(D * 2, in_channels, kernel_size=3, stride=1, padding=1)
        # ===== end of code ====

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        assert x.shape[-2:] == (28, 28), "Expect input shape to be (28, 28)."
        # ===== your code here! ====
        # Encoder
        x1 = self.enc1(x)       # (B, D, 28, 28)
        x2 = self.enc2(x1)      # (B, D, 14, 14)
        x3 = self.enc3(x2)      # (B, D, 7, 7)

        # Bottleneck
        xb = self.flatten(x3)   # (B, D, 1, 1)
        xb = self.mid(xb)       # (B, D, 1, 1)
        xb = self.unflatten(xb) # (B, D, 7, 7)

        # Decoder with skip connections
        d3 = self.dec3(torch.cat([xb, x3], dim=1))  # (B, D, 14, 14)
        d2 = self.dec2(torch.cat([d3, x2], dim=1))  # (B, D, 28, 28)
        out = self.out_conv(torch.cat([d2, x1], dim=1))  # (B, in_ch, 28, 28)
        return out
        # ===== end of code ====

