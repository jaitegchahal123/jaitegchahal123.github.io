class TimeConditionalUNet(nn.Module):
    def __init__(
        self,
        in_channels: int,
        num_classes: int,
        num_hiddens: int,
    ):
        super().__init__()
        # ===== your code here! ====
        self.in_channels = in_channels
        self.num_hiddens = num_hiddens

        D = num_hiddens

        # Encoder
        self.enc1 = ConvBlock(in_channels, D)   # 28x28
        self.enc2 = DownBlock(D, D)            # 14x14
        self.enc3 = DownBlock(D, D)            # 7x7

        # Bottleneck
        self.flatten = Flatten()               # 7x7 -> 1x1
        self.mid = ConvBlock(D, D)             # stays 1x1
        self.unflatten = Unflatten(D)          # 1x1 -> 7x7

        # Decoder with skip connections
        self.dec3 = UpBlock(D * 2, D)          # 7x7 -> 14x14
        self.dec2 = UpBlock(D * 2, D)          # 14x14 -> 28x28
        self.out_conv = nn.Conv2d(D * 2, in_channels, kernel_size=3, stride=1, padding=1)

        # Time embedding MLP: t ∈ ℝ → ℝ^D
        self.time_mlp = FCBlock(1, D)
        # ===== end of code ====

    def forward(
        self,
        x: torch.Tensor,
        t: torch.Tensor,
    ) -> torch.Tensor:
        """
        Args:
            x: (N, C, H, W) input tensor.
            t: (N,) normalized time tensor.

        Returns:
            (N, C, H, W) output tensor.
        """
        assert x.shape[-2:] == (28, 28), "Expect input shape to be (28, 28)."
        # ===== your code here! ====
        N = x.shape[0]

        # Encoder
        x1 = self.enc1(x)       # (N, D, 28, 28)
        x2 = self.enc2(x1)      # (N, D, 14, 14)
        x3 = self.enc3(x2)      # (N, D, 7, 7)

        # Bottleneck
        xb = self.flatten(x3)   # (N, D, 1, 1)

        # Time embedding: (N,) -> (N, D, 1, 1)
        t_in = t.view(N, 1)
        t_emb = self.time_mlp(t_in)            # (N, D)
        t_emb = t_emb.view(N, self.num_hiddens, 1, 1)

        xb = xb + t_emb                         # inject time
        xb = self.mid(xb)
        xb = self.unflatten(xb)                 # (N, D, 7, 7)

        # Decoder with skip connections
        d3 = self.dec3(torch.cat([xb, x3], dim=1))  # (N, D, 14, 14)
        d2 = self.dec2(torch.cat([d3, x2], dim=1))  # (N, D, 28, 28)
        out = self.out_conv(torch.cat([d2, x1], dim=1))  # (N, C, 28, 28)
        return out
        # ===== end of code ====
        raise NotImplementedError()

"""## Implementing the Forward and Reverse Process for Time-conditioned Denoising"""

def time_fm_forward(
    unet: TimeConditionalUNet,
    x_1: torch.Tensor,
    num_ts: int,
) -> torch.Tensor:
    """Algorithm 1

    Args:
        unet: TimeConditionalUNet
        x_1: (N, C, H, W) input tensor.
        num_ts: int, number of timesteps.
    Returns:
        (,) loss.
    """
    unet.train()
    # ===== your code here! ====
    device = x_1.device
    N = x_1.shape[0]

    # Sample starting noise x_0 ~ N(0, I)
    x_0 = torch.randn_like(x_1)

    # Sample t ~ U(0, 1) per sample
    t = torch.rand(N, device=device)

    # Broadcast t to image shape
    t_broadcast = t.view(N, 1, 1, 1)

    # Linear interpolation along path
    x_t = (1.0 - t_broadcast) * x_0 + t_broadcast * x_1

    # Target velocity (constant along the path for linear interpolation)
    v_target = x_1 - x_0

    # Predicted velocity from UNet
    v_pred = unet(x_t, t)

    # MSE loss
    loss = torch.mean((v_pred - v_target) ** 2)
    return loss
    # ===== end of code ====
    raise NotImplementedError()

@torch.inference_mode()
def time_fm_sample(
    unet: TimeConditionalUNet,
    img_wh: tuple[int, int],
    num_ts: int,
    seed: int = 0,
) -> torch.Tensor:
    """Algorithm 2

    Args:
        unet: TimeConditionalUNet
        img_wh: (H, W) output image width and height.
        num_ts: int, number of timesteps.
        seed: int, random seed.

    Returns:
        (N, C, H, W) final sample.
    """
    unet.eval()
    # ===== your code here! ====
    device = next(unet.parameters()).device
    H, W = img_wh

    torch.manual_seed(seed)

    N = 16   # number of samples to generate
    C = 1    # MNIST digits are grayscale

    # Start from Gaussian noise at t = 0
    x = torch.randn(N, C, H, W, device=device)

    dt = 1.0 / num_ts

    for k in range(num_ts):
        t_val = k / num_ts
        t = torch.full((N,), t_val, device=device)
        v = unet(x, t)               # predicted velocity
        x = x + dt * v               # Euler step

    return x.detach().cpu()
    # ===== end of code ====
    raise NotImplementedError()

class TimeConditionalFM(nn.Module):
    def __init__(
        self,
        unet: TimeConditionalUNet,
        num_ts: int = 50,
        img_hw: tuple[int, int] = (28, 28),
    ):
        super().__init__()

        self.unet = unet
        self.num_ts = num_ts
        self.img_hw = img_hw


    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        Args:
            x: (N, C, H, W) input tensor.

        Returns:
            (,) diffusion loss.
        """
        return time_fm_forward(
            self.unet, x, self.num_ts
        )


    @torch.inference_mode()
    def sample(
        self,
        img_wh: tuple[int, int],
        seed: int = 0,
    ):
        return time_fm_sample(
            self.unet, img_wh, self.num_ts, seed
        )

